-- Tabla protocolo
CREATE TABLE protocolo (
  protocolo_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR2(50) NOT NULL,
  enfermedad VARCHAR2(50) NOT NULL,
  linea VARCHAR2(20) NOT NULL
);

-- Tabla ciclo
CREATE TABLE ciclo (
  protocolo_id NUMBER NOT NULL,
  ciclo_id NUMBER NOT NULL,
  regimen NUMBER NOT NULL,
  duracion_semanas NUMBER,
  ciclo_final CHAR(1) CHECK (ciclo_final IN ('0','1')),
  repeticiones NUMBER,
  PRIMARY KEY (protocolo_id, ciclo_id, regimen),
  FOREIGN KEY (protocolo_id) REFERENCES protocolo(protocolo_id)
);

-- Tabla drogas
CREATE TABLE droga (
  id_droga NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_farmacia VARCHAR2(50),
  medicamento VARCHAR2(100) NOT NULL,
  presentacion VARCHAR2(100) NOT NULL,
  dosis NUMBER,
  dosis_unidad VARCHAR2(20),
  dosis_maxima NUMBER,
  dosis_maxima_unidad VARCHAR2(20)
);

-- Tabla administracion_medicacion
CREATE TABLE administracion_medicacion (
  id NUMBER GENERATED ALWAYS AS IDENTITY,
  protocolo_id NUMBER NOT NULL,
  ciclo_id NUMBER NOT NULL,
  regimen NUMBER NOT NULL,
  id_droga NUMBER NOT NULL,
  dosis NUMBER,
  dosis_unidad VARCHAR2(20),
  frecuencia VARCHAR2(100),
  administracion_diaria NUMBER,
  frecuencia_diaria NUMBER,
  PRIMARY KEY (protocolo_id, ciclo_id, regimen, id_droga),
  FOREIGN KEY (protocolo_id, ciclo_id, regimen) REFERENCES ciclo(protocolo_id, ciclo_id, regimen),
  FOREIGN KEY (id_droga) REFERENCES droga(id_droga)
);

-- Tabla profesional
CREATE TABLE profesional (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR2(100) NOT NULL,
  apellido VARCHAR2(100) NOT NULL,
  dni VARCHAR2(10) NOT NULL,
  matricula VARCHAR2(20),
  especialidad VARCHAR2(100)
);

-- Tabla paciente
CREATE TABLE paciente (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR2(100) NOT NULL,
  apellido VARCHAR2(100) NOT NULL,
  id_hospitalario VARCHAR2(30) NOT NULL,
  fecha_nacimiento DATE,
  peso FLOAT,
  ultima_modificacion TIMESTAMP,
  sexo CHAR(1) CHECK (sexo IN ('M','F')),
  profesional_id NUMBER,
  obra_social VARCHAR2(100),
  FOREIGN KEY (profesional_id) REFERENCES profesional(id)
);

-- Tabla tratamiento_paciente
CREATE TABLE tratamiento_paciente (
  id NUMBER GENERATED ALWAYS AS IDENTITY,
  id_paciente NUMBER NOT NULL,
  ciclo_id NUMBER NOT NULL,
  protocolo_id NUMBER NOT NULL,
  regimen NUMBER NOT NULL,
  fecha_receta DATE NOT NULL,
  estado_del_tratamiento VARCHAR2(100),
  PRIMARY KEY (id_paciente, ciclo_id, protocolo_id, regimen, fecha_receta),
  FOREIGN KEY (id_paciente) REFERENCES paciente(id),
  FOREIGN KEY (protocolo_id, ciclo_id, regimen) REFERENCES ciclo(protocolo_id, ciclo_id, regimen)
);

-- Índices adicionales para búsquedas eficientes
CREATE INDEX idx_paciente_nombre ON paciente(nombre, apellido);
CREATE INDEX idx_tratamiento_paciente_fecha ON tratamiento_paciente(fecha_receta);

-- Índice para buscar protocolos por nombre
CREATE INDEX idx_protocolo_nombre ON protocolo(nombre);

-- Índice para buscar drogas por nombre
CREATE INDEX idx_drogas_nombre ON droga(medicamento);